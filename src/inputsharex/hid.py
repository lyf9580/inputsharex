def mouse_report(buttons: int, dx: int, dy: int, wheel: int = 0, pan: int = 0) -> bytes:
    """单帧鼠标报文；dx/dy 超过 ±127 时由调用方拆分。"""
    def clamp(v: int) -> int:
        return max(-127, min(127, v))

    return bytes([buttons & 0x1F, clamp(dx) & 0xFF, clamp(dy) & 0xFF, clamp(wheel) & 0xFF, clamp(pan) & 0xFF])


def mouse_reports(buttons: int, dx: int, dy: int, wheel: int = 0, pan: int = 0):
    """把一次大位移拆成多帧，保证最后一帧带上按键状态。"""
    out = []
    sx = 1 if dx > 0 else -1
    sy = 1 if dy > 0 else -1
    remaining_x, remaining_y = abs(dx), abs(dy)
    while remaining_x or remaining_y:
        step_x = min(remaining_x, 127) * sx
        step_y = min(remaining_y, 127) * sy
        remaining_x -= abs(step_x)
        remaining_y -= abs(step_y)
        out.append(mouse_report(buttons, step_x, step_y))
    if wheel or pan:
        out.append(mouse_report(buttons, 0, 0, wheel, pan))
    if not out:
        out.append(mouse_report(buttons, 0, 0))
    return out


def keyboard_report(modifiers: int = 0, keys=()) -> bytes:
    """标准 6KRO 键盘报文：修饰键字节 + 保留字节 + 最多 6 个按键 usage。"""
    pressed = [int(k) & 0xFF for k in list(keys)[:6] if 0 < int(k) < 0xE8]
    while len(pressed) < 6:
        pressed.append(0)
    return bytes([modifiers & 0xFF, 0x00, *pressed])
